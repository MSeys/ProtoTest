// One changelog source: the repository's CHANGELOG.md. This script generates the documentation page and
// the homepage release feed from it, so a release is written once. Run without arguments to write the
// files; run with --check to fail when they are stale (./proto docs check uses that mode).

import {readFileSync, writeFileSync, existsSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const docsRoot = path.resolve(here, '..');
const repoRoot = path.resolve(docsRoot, '..');
const sourcePath = path.join(repoRoot, 'CHANGELOG.md');
const pagePath = path.join(docsRoot, 'src', 'pages', 'changelog.md');
const dataPath = path.join(docsRoot, 'src', 'data', 'changelog.generated.ts');
const check = process.argv.includes('--check');

const source = readFileSync(sourcePath, 'utf8');

// Split the Keep a Changelog file into its sections. Everything before the first `## ` heading is the
// file's own introduction.
const sections = [];
let current = null;
for (const line of source.split(/\r?\n/)) {
  const heading = /^##\s+(.*)$/.exec(line);
  if (heading) {
    current = {title: heading[1].trim(), lines: []};
    sections.push(current);
  } else if (current) {
    current.lines.push(line);
  }
}

function bodyOf(section) {
  const lines = [...section.lines];
  while (lines.length > 0 && lines[lines.length - 1].trim() === '') lines.pop();
  // The link-reference block at the end (`[1.0.0]: https://...`) belongs to the repository file.
  while (lines.length > 0 && /^\[[^\]]+\]:\s+\S+/.test(lines[lines.length - 1].trim())) {
    lines.pop();
    while (lines.length > 0 && lines[lines.length - 1].trim() === '') lines.pop();
  }
  return lines.join('\n').trim();
}

function summarize(body) {
  // Blocks are separated by blank lines, so a wrapped bullet stays one block and its indented
  // continuation lines are never mistaken for an introduction.
  const blocks = body
    .split(/\n\s*\n/)
    .map((block) => block.split('\n').map((line) => line.trim()).filter(Boolean))
    .filter((block) => block.length > 0);

  let text = '';
  let isBullet = false;
  for (const block of blocks) {
    const first = block[0];
    if (first.startsWith('#') || first.startsWith('|') || first.startsWith('```')) continue;
    if (first.startsWith('- ')) {
      // One bullet with its indented continuation lines; the next bullet starts a new entry.
      const bullet = [first.slice(2)];
      for (let index = 1; index < block.length; index++) {
        if (block[index].startsWith('- ')) break;
        bullet.push(block[index]);
      }
      text = bullet.join(' ');
      isBullet = true;
    } else {
      text = block.join(' ');
    }

    break;
  }

  text = text
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/[*`]/g, '')
    .replace(/\s+/g, ' ')
    .trim();

  // Keep whole sentences: one at minimum, a second one when it fits the feed. A bullet summarizes as
  // its first sentence (unless that sentence is too thin to stand alone).
  const sentences = text.split(/(?<=[.!?])\s+/);
  let summary = '';
  let count = 0;
  for (const sentence of sentences) {
    if (summary && (summary.length >= 140 || summary.length + 1 + sentence.length > 240)) break;
    summary = summary ? `${summary} ${sentence}` : sentence;
    count++;
    if (isBullet && count >= 1 && summary.length >= 60) break;
  }

  if (summary.length > 240) {
    const cut = summary.slice(0, 240);
    const sentenceEnd = cut.lastIndexOf('. ');
    summary = sentenceEnd > 60 ? cut.slice(0, sentenceEnd + 1) : `${cut.trimEnd()}...`;
  }

  return summary;
}

const releases = [];
for (const section of sections) {
  const released = /^\[(\d+\.\d+\.\d+)\]\s*-\s*(\d{4}-\d{2}-\d{2})$/.exec(section.title);
  if (!released) continue;
  const body = bodyOf(section);
  if (body === '') continue;
  releases.push({version: released[1], date: released[2], summary: summarize(body), body});
}

if (releases.length === 0) {
  console.error(`[changelog] no released sections found in ${sourcePath}`);
  process.exit(1);
}

const page = [
  '---',
  'title: Changelog',
  'description: What changed in each ProtoTest release, with every breaking change and how to update for it.',
  '---',
  '',
  '{/* Generated from the repository CHANGELOG.md by docs/scripts/generate-changelog.mjs. Do not edit this file. */}',
  '',
  '# Changelog',
  '',
  'Every ProtoTest package shares one version number, so this page lists releases, not packages. Each release that changes a public API lists the change under **Breaking changes**, with what to write instead.',
  '',
  'Work in progress is tracked in the repository [CHANGELOG.md](https://github.com/MSeys/ProtoTest/blob/main/CHANGELOG.md).',
  '',
  ...releases.flatMap((release) => [`## ${release.version} - ${release.date}`, '', release.body, '']),
].join('\n');

const data = [
  '// Generated from CHANGELOG.md by docs/scripts/generate-changelog.mjs. Do not edit this file.',
  '',
  'export interface ChangelogRelease {',
  '  version: string;',
  '  date: string;',
  '  summary: string;',
  '  body: string;',
  '}',
  '',
  `export const releases: ChangelogRelease[] = ${JSON.stringify(releases, null, 2)};`,
  '',
].join('\n');

if (check) {
  let stale = false;
  for (const [target, expected] of [
    [pagePath, page],
    [dataPath, data],
  ]) {
    const actual = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (actual !== expected) {
      console.error(`[changelog] stale: ${path.relative(repoRoot, target)}`);
      stale = true;
    }
  }

  if (stale) {
    console.error('[changelog] run: node docs/scripts/generate-changelog.mjs');
    process.exit(1);
  }

  console.log(`[changelog] up to date (${releases.length} releases)`);
  process.exit(0);
}

writeFileSync(pagePath, page);
writeFileSync(dataPath, data);
console.log(`[changelog] wrote ${releases.length} releases to docs/src/pages/changelog.md and docs/src/data/changelog.generated.ts`);
